/**
 * Renders a resolved CV to a self-contained LaTeX document.
 *
 * Every string that originates in the data files passes through `escapeLatex`
 * here, at the render boundary, and nowhere else. Data files hold plain text.
 */

import type { Rich, RenderEntry, RenderSection, ResolvedCv } from "@/lib/cv/types";
import { escapeLatex, escapeLatexUrl } from "./escape";

const SEPARATOR = " \\textbullet{} ";

/**
 * Link display text — URLs and DOIs — contains no natural hyphenation points,
 * so TeX cannot break it and the line runs into the margin. Permitting breaks
 * after path slashes fixes that without changing what is displayed. Dots and
 * colons are not break points: they invite fragments like "doi:10." at a
 * line end.
 */
function allowBreaks(value: string): string {
  return value.replace(/\//g, "/\\allowbreak{}");
}

/**
 * Ties month to year ("Jun 2022" -> "Jun~2022") so running text never breaks
 * a date across lines. Runs after escaping; escapeLatex would escape the ~.
 */
function tieDates(value: string): string {
  return value.replace(
    /\b(Jan|Feb|Mar|Apr|May|Jun|Jul|Aug|Sep|Oct|Nov|Dec) (\d{4})/g,
    "$1~$2",
  );
}

export function renderRich(runs: Rich): string {
  return runs
    .map((run) => {
      let out = tieDates(escapeLatex(run.text));
      if (run.bold) out = `\\textbf{${out}}`;
      if (run.italic) out = `\\textit{${out}}`;
      if (run.href) {
        out = `\\href{${escapeLatexUrl(run.href)}}{${allowBreaks(out)}}`;
      }
      return out;
    })
    .join("");
}

function macro(name: string, ...args: string[]): string {
  return `\\${name}${args.map((arg) => `{${arg}}`).join("")}`;
}

function renderBullets(bullets: Rich[]): string[] {
  if (bullets.length === 0) return [];
  return [
    "\\begin{itemize}",
    ...bullets.map((bullet) => `  \\item ${renderRich(bullet)}`),
    "\\end{itemize}",
  ];
}

function renderEntry(entry: RenderEntry): string[] {
  const lines = [
    macro(
      "cventry",
      escapeLatex(entry.dates ?? ""),
      renderRich(entry.heading),
      entry.subheading ? renderRich(entry.subheading) : "",
      escapeLatex(entry.location ?? ""),
    ),
  ];

  if (entry.summary) lines.push(macro("cvnote", tieDates(escapeLatex(entry.summary))));
  if (entry.chips?.length) {
    lines.push(macro("cvchips", entry.chips.map(escapeLatex).join(" \\textperiodcentered{} ")));
  }
  lines.push(...renderBullets(entry.bullets));
  return lines;
}

function renderSection(section: RenderSection): string[] {
  // 6.5 lines covers the heading block plus the first entry's own needspace,
  // so a section title can never be stranded at a page bottom. The skills
  // block is short and fixed, so its full height is reserved instead: the
  // label column reads badly when split from its heading by a page break.
  const reserve =
    section.layout === "skills"
      ? `${3 * (section.groups?.length ?? 0) + 4}\\baselineskip`
      : "6.5\\baselineskip";
  const lines = ["", `\\needspace{${reserve}}`, macro("section", escapeLatex(section.title))];

  switch (section.layout) {
    case "prose":
      if (section.prose) lines.push(macro("cvprose", escapeLatex(section.prose)));
      lines.push(...renderBullets(section.bullets ?? []));
      break;

    case "skills":
      for (const group of section.groups ?? []) {
        lines.push(
          macro(
            "cvskill",
            escapeLatex(group.label),
            group.items.map(escapeLatex).join(", "),
          ),
        );
      }
      break;

    case "numbered":
      lines.push("\\begin{enumerate}");
      for (const entry of section.entries) {
        lines.push(`  \\item ${renderRich(entry.heading)}`);
      }
      lines.push("\\end{enumerate}");
      break;

    case "entries":
      for (const entry of section.entries) lines.push(...renderEntry(entry));
      break;
  }

  return lines;
}

function renderContactLine(resolved: ResolvedCv): string {
  const { profile } = resolved;
  const parts = [
    `\\href{mailto:${escapeLatexUrl(profile.email)}}{${escapeLatex(profile.email)}}`,
    escapeLatex(profile.location),
    ...profile.links.map(
      (item) =>
        `\\href{${escapeLatexUrl(item.url)}}{${escapeLatex(item.display)}}`,
    ),
  ];
  return parts.join(SEPARATOR);
}

export function renderLatexDocument(
  resolved: ResolvedCv,
  preamble: string,
): string {
  const { profile } = resolved;

  const lines = [
    `% Generated by scripts/generate-tex.ts from src/data/cv. Do not edit by hand.`,
    `% Variant: ${resolved.variant.id} (${resolved.variant.label})`,
    `% Compile: xelatex -interaction=nonstopmode <file>.tex  (run twice)`,
    "",
    preamble.trimEnd(),
    "",
    macro("renewcommand", "\\cvfullname", escapeLatex(profile.name)),
    "",
    "\\begin{document}",
    "",
    macro(
      "cvheader",
      escapeLatex(profile.name),
      escapeLatex(profile.credentials),
      escapeLatex(profile.headline),
      renderContactLine(resolved),
    ),
    ...resolved.sections.flatMap(renderSection),
    "",
    "\\end{document}",
    "",
  ];

  return lines.join("\n");
}
